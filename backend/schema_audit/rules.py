"""The rule set. Every rule is a pure function: Schema in, findings out.

Identifiers, DDL and these comments stay English like the rest of the codebase;
the prose a rule produces is Turkish, because that text is read by whoever has
to act on the finding.

Two things are deliberate here. Rules never run SQL, so they can be exercised
against a hand-built Schema in a test. And a rule that cannot know the right
answer says so through Remediation.requires_decision instead of guessing - the
correct ON DELETE for a business table is a policy question, not a lookup.
"""

from .model import ERROR, INFO, WARNING, Finding, Remediation, Schema


def _q(schema: Schema, table: str) -> str:
    return f"{schema.name}.{table}"


def _recreate_fk(schema: Schema, fk, on_delete: str, on_update: str) -> str:
    """DDL that replaces a foreign key with one that spells out both actions.

    Dropping and re-adding inside a single ALTER TABLE keeps it atomic, so the
    table is never briefly unconstrained.
    """
    columns = ", ".join(fk.columns)
    target_columns = ", ".join(fk.target_columns)
    return (
        f"ALTER TABLE {_q(schema, fk.table)}\n"
        f"    DROP CONSTRAINT {fk.name},\n"
        f"    ADD CONSTRAINT {fk.name}\n"
        f"        FOREIGN KEY ({columns})\n"
        f"        REFERENCES {_q(schema, fk.target_table)} ({target_columns})\n"
        f"        ON DELETE {on_delete} ON UPDATE {on_update};"
    )


# --------------------------------------------------------------------------
# R001 - primary key
# --------------------------------------------------------------------------


def missing_primary_key(schema: Schema) -> list[Finding]:
    findings = []
    for name in sorted(schema.tables):
        table = schema.tables[name]
        if table.primary_key:
            continue

        remediations = []
        for unique in table.unique_sets:
            columns = ", ".join(unique)
            remediations.append(
                Remediation(
                    label=f"Mevcut UNIQUE ({columns}) kısıtını birincil anahtara yükselt",
                    ddl=f"ALTER TABLE {_q(schema, name)} ADD PRIMARY KEY ({columns});",
                    risk="medium",
                    recommended=True,
                    note="Listedeki her kolonun önce NOT NULL olması gerekir.",
                )
            )
        remediations.append(
            Remediation(
                label="Yapay (surrogate) anahtar kolonu ekle",
                ddl=(
                    f"ALTER TABLE {_q(schema, name)}\n"
                    f"    ADD COLUMN id integer GENERATED BY DEFAULT AS IDENTITY"
                    f" PRIMARY KEY;"
                ),
                risk="medium",
                recommended=not table.unique_sets,
                note=(
                    "Tabloyu baştan yazar; büyük bir tabloda bakım penceresinde "
                    "çalıştır."
                ),
            )
        )

        findings.append(
            Finding(
                rule_id="R001",
                rule_name="Birincil anahtar yok",
                severity=ERROR,
                target=_q(schema, name),
                message=f'"{name}" tablosunda birincil anahtar yok.',
                rationale=(
                    "Birincil anahtar olmadan tek bir satırı adresleyebilmenin "
                    "yolu yoktur; yinelenen kayıtlar engellenemez, başka hiçbir "
                    "tablo bu tabloya referans veremez ve çoğu replikasyon ile "
                    "ORM aracı tabloyla çalışmayı reddeder."
                ),
                remediations=tuple(remediations),
            )
        )
    return findings


# --------------------------------------------------------------------------
# R002 / R003 - referential actions
# --------------------------------------------------------------------------


def undefined_on_delete(schema: Schema) -> list[Finding]:
    findings = []
    for fk in schema.foreign_keys:
        if fk.on_delete != "NO ACTION":
            continue

        table = schema.tables[fk.table]
        nullable = all(
            (column := table.column(name)) is not None and not column.not_null
            for name in fk.columns
        )

        remediations = []
        if schema.is_junction(fk.table):
            remediations.append(
                Remediation(
                    label="Bağlantı satırını üst kayıtla birlikte sil",
                    ddl=_recreate_fk(schema, fk, "CASCADE", fk.on_update),
                    risk="medium",
                    recommended=True,
                    note=(
                        f'"{fk.table}" bir bağlantı tablosu; ilgili '
                        f"{fk.target_table} satırı gidince buradaki satırın "
                        f"anlamı kalmaz."
                    ),
                )
            )
        else:
            remediations.append(
                Remediation(
                    label="Alt kayıt varken silmeyi reddet (açıkça yaz)",
                    ddl=_recreate_fk(schema, fk, "RESTRICT", fk.on_update),
                    risk="low",
                    recommended=True,
                    note=(
                        "Veritabanının bugün yaptığının aynısı - bu yalnızca "
                        "niyeti şemada görünür kılar."
                    ),
                )
            )
            if nullable:
                remediations.append(
                    Remediation(
                        label="Alt kaydı koru, referansı boşalt",
                        ddl=_recreate_fk(schema, fk, "SET NULL", fk.on_update),
                        risk="medium",
                        requires_decision=True,
                        note=(
                            f"Bir {fk.table} satırı, bağlı olduğu "
                            f"{fk.target_table} kaydından sonra da yaşamalıysa "
                            f"bunu seç."
                        ),
                    )
                )
            remediations.append(
                Remediation(
                    label="Alt kayıtları da sil",
                    ddl=_recreate_fk(schema, fk, "CASCADE", fk.on_update),
                    risk="high",
                    requires_decision=True,
                    note=(
                        f"Yıkıcı: tek bir {fk.target_table} satırını silmek, "
                        f"eşleşen bütün {fk.table} satırlarını sessizce siler."
                    ),
                )
            )

        findings.append(
            Finding(
                rule_id="R002",
                rule_name="Tanımsız ON DELETE davranışı",
                severity=WARNING,
                target=fk.name,
                message=f"{fk.label} ilişkisi ON DELETE NO ACTION'a düşüyor.",
                rationale=(
                    "Katalog, hiç yazılmamış bir ifadeyi açıkça yazılmış "
                    "ON DELETE NO ACTION'dan ayırt edemez; sorunun kendisi de "
                    "budur: okuyan kişi silmeyi reddetmenin bilinçli bir karar "
                    "mı yoksa gözden kaçmış bir eksik mi olduğunu anlayamaz. "
                    "Davranışı açıkça yazmak, hiçbir şeyi değiştirmeden bu "
                    "belirsizliği ortadan kaldırır."
                ),
                remediations=tuple(remediations),
            )
        )
    return findings


def undefined_on_update(schema: Schema) -> list[Finding]:
    findings = []
    for fk in schema.foreign_keys:
        if fk.on_update != "NO ACTION":
            continue
        findings.append(
            Finding(
                rule_id="R003",
                rule_name="Tanımsız ON UPDATE davranışı",
                severity=INFO,
                target=fk.name,
                message=f"{fk.label} ilişkisi ON UPDATE NO ACTION'a düşüyor.",
                rationale=(
                    "Referans verilen anahtar otomatik üretiliyor ve hiç "
                    "değiştirilmiyorsa önceliği düşüktür, çünkü bu davranış hiç "
                    "tetiklenmez. Yine de şemanın bu varsayımın sonsuza kadar "
                    "geçerli kalmasına dayanmaması için yazılmaya değer."
                ),
                remediations=(
                    Remediation(
                        label="Mevcut davranışı açıkça belirt",
                        ddl=_recreate_fk(schema, fk, fk.on_delete, "RESTRICT"),
                        risk="low",
                        recommended=True,
                        note="Davranış değişmez; yalnızca niyeti belgeler.",
                    ),
                    Remediation(
                        label="Üst anahtar değişince onu takip et",
                        ddl=_recreate_fk(schema, fk, fk.on_delete, "CASCADE"),
                        risk="medium",
                        requires_decision=True,
                        note=(
                            "Yalnızca referans verilen anahtar güncelleniyorsa "
                            "gereklidir."
                        ),
                    ),
                ),
            )
        )
    return findings


