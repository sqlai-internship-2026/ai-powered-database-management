# R008 - unindexed foreign keys
# --------------------------------------------------------------------------


def unindexed_foreign_key(schema: Schema) -> list[Finding]:
    findings = []
    for fk in schema.foreign_keys:
        table = schema.tables.get(fk.table)
        if table is None or not fk.columns:
            continue
        if any(index.covers(fk.columns) for index in table.indexes):
            continue

        columns = ", ".join(fk.columns)
        index_name = f"idx_{fk.table}_{'_'.join(fk.columns)}"
        findings.append(
            Finding(
                rule_id="R008",
                rule_name="İndekslenmemiş foreign key",
                severity=WARNING,
                target=f"{_q(schema, fk.table)}.{columns}",
                message=(
                    f"{fk.table} tablosunda ({columns}) ile başlayan bir index "
                    f"yok."
                ),
                rationale=(
                    "PostgreSQL foreign key'in üst tarafını indeksler, alt "
                    "tarafını asla. Bu ilişki üzerinden yapılan her join ve üst "
                    "tabloda yapılan her silme - ki alt kayıtları aramak "
                    "zorundadır - sıralı taramaya düşer. Bileşik birincil "
                    "anahtarda yalnızca ilk kolon kapsandığı için bağlantı "
                    "tablolarının ikinci kolonu genelde buraya düşer."
                ),
                remediations=(
                    Remediation(
                        label=f"({columns}) üzerinde index oluştur",
                        ddl=(
                            f"CREATE INDEX {index_name}\n"
                            f"    ON {_q(schema, fk.table)} ({columns});"
                        ),
                        risk="low",
                        recommended=True,
                        note=(
                            "Yoğun bir tabloda yazma kilidi almamak için "
                            "CONCURRENTLY ekle."
                        ),
                    ),
                ),
            )
        )
    return findings


# --------------------------------------------------------------------------
# R009 - relationships the database does not enforce
# --------------------------------------------------------------------------


def _guess_target_table(schema: Schema, base: str) -> str | None:
    candidates = [base, f"{base}s", f"{base}es"]
    if base.endswith("y"):
        candidates.append(f"{base[:-1]}ies")
    for candidate in candidates:
        if candidate in schema.tables:
            return candidate
    return None


def implied_foreign_key(schema: Schema) -> list[Finding]:
    findings = []
    for name in sorted(schema.tables):
        table = schema.tables[name]
        constrained = {column for fk in schema.outgoing(name) for column in fk.columns}
        for column in table.columns:
            if not column.name.endswith("_id") or column.name in constrained:
                continue
            target = _guess_target_table(schema, column.name[:-3])
            if target is None or target == name:
                continue

            findings.append(
                Finding(
                    rule_id="R009",
                    rule_name="Foreign key ile korunmayan örtük ilişki",
                    severity=WARNING,
                    target=f"{_q(schema, name)}.{column.name}",
                    message=(
                        f'"{name}.{column.name}" bir "{target}" referansına '
                        f"benziyor ama bunu zorlayan bir foreign key yok."
                    ),
                    rationale=(
                        "Hiçbir üst satırla eşleşmeyen bir değeri engelleyen "
                        "yok. Veritabanı yetim kayıtları sessizce saklar; "
                        "bunlar genellikle çok sonra, inner join'den düşen "
                        "satırlar olarak ortaya çıkar."
                    ),
                    confidence="heuristic",
                    remediations=(
                        Remediation(
                            label="Önce yetim kayıtları kontrol et",
                            ddl=(
                                f"SELECT COUNT(*)\n"
                                f"FROM {_q(schema, name)} child\n"
                                f"LEFT JOIN {_q(schema, target)} parent\n"
                                f"       ON parent.id = child.{column.name}\n"
                                f"WHERE child.{column.name} IS NOT NULL\n"
                                f"  AND parent.id IS NULL;"
                            ),
                            risk="low",
                            recommended=True,
                            note=(
                                "Salt okunur. Aşağıdaki kısıt, bu sorgu 0 "
                                "dönene kadar eklenemez."
                            ),
                        ),
                        Remediation(
                            label="Foreign key'i ekle",
                            ddl=(
                                f"ALTER TABLE {_q(schema, name)}\n"
                                f"    ADD CONSTRAINT {name}_{column.name}_fkey\n"
                                f"        FOREIGN KEY ({column.name})\n"
                                f"        REFERENCES {_q(schema, target)} (id)\n"
                                f"        ON DELETE RESTRICT ON UPDATE RESTRICT;"
                            ),
                            risk="medium",
                            requires_decision=True,
                            note=(
                                "Tahmin edilen hedef tablonun doğru olduğunu "
                                "teyit et."
                            ),
                        ),
                    ),
                )
            )
    return findings


# --------------------------------------------------------------------------
# R010 - the same column name declared differently
# --------------------------------------------------------------------------


def inconsistent_column_type(schema: Schema) -> list[Finding]:
    usage: dict[str, dict[str, list[str]]] = {}
    for name in sorted(schema.tables):
        for column in schema.tables[name].columns:
            usage.setdefault(column.name, {}).setdefault(column.data_type, []).append(
                name
            )

    findings = []
    for column_name in sorted(usage):
        variants = usage[column_name]
        if len(variants) < 2:
            continue

        # The type used by the most tables wins; ties go to the longer
        # declaration, since that is the one able to hold every existing value.
        preferred = sorted(
            variants,
            key=lambda type_name: (-len(variants[type_name]), -len(type_name)),
        )[0]
        summary = "; ".join(
            f"{', '.join(sorted(tables))} tablosunda {type_name}"
            for type_name, tables in sorted(variants.items())
        )

        remediations = []
        for type_name, tables in sorted(variants.items()):
            if type_name == preferred:
                continue
            for table_name in sorted(tables):
                remediations.append(
                    Remediation(
                        label=(
                            f"{table_name}.{column_name} kolonunu {preferred} "
                            f"tipine hizala"
                        ),
                        ddl=(
                            f"ALTER TABLE {_q(schema, table_name)}\n"
                            f"    ALTER COLUMN {column_name} TYPE {preferred};"
                        ),
                        risk="medium",
                        requires_decision=True,
                        note=(
                            "Yalnızca iki kolon gerçekten aynı türde veri "
                            "tutuyorsa - ortak ad bunun kanıtı değildir."
                        ),
                    )
                )

        findings.append(
            Finding(
                rule_id="R010",
                rule_name="Ortak kolon adı için tutarsız tip",
                severity=INFO,
                target=column_name,
                message=(
                    f'"{column_name}" kolonu farklı tiplerde tanımlanmış: '
                    f"{summary}."
                ),
                rationale=(
                    "Aynı anlama gelen kolonlar aynı şekilde tanımlanmalıdır. "
                    "Karışık genişlikler, bir tabloya sığan ama aynı veri başka "
                    "tabloya taşındığında reddedilen değerlere yol açar."
                ),
                confidence="heuristic",
                remediations=tuple(remediations),
            )
        )
    return findings
