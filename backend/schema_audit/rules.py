def isolated_table(schema: Schema) -> list[Finding]:
    findings = []
    for name in sorted(schema.tables):
        if schema.outgoing(name) or schema.incoming(name):
            continue
        findings.append(
            Finding(
                rule_id="R004",
                rule_name="İlişkisiz tablo",
                severity=INFO,
                target=_q(schema, name),
                message=(
                    f'"{name}" tablosuna hiçbir yönde foreign key uğramıyor.'
                ),
                rationale=(
                    "Ya gerçekten tek başına duruyordur - bir kod listesi, "
                    "denetim kaydı, migration defteri - ya da uygulama kodunda, "
                    "veritabanının zorlamadığı bir ilişki üzerinden "
                    "birleştiriliyordur. Yetim satırlar ikinci durumdan doğar."
                ),
                confidence="heuristic",
                remediations=(
                    Remediation(
                        label="Tablonun bilinçli olarak bağımsız olduğunu doğrula",
                        ddl="",
                        risk="low",
                        recommended=True,
                        note=(
                            "Öyleyse kuralın yoksayma listesine ekle ki rapor "
                            "bilinen-doğru bulgularla dolmasın."
                        ),
                    ),
                    Remediation(
                        label="Eksik ilişkiyi tanımla",
                        ddl=(
                            f"ALTER TABLE {_q(schema, name)}\n"
                            f"    ADD CONSTRAINT {name}_<ust_tablo>_id_fkey\n"
                            f"        FOREIGN KEY (<ust_tablo>_id)\n"
                            f"        REFERENCES {schema.name}.<ust_tablo> (id)\n"
                            f"        ON DELETE RESTRICT ON UPDATE RESTRICT;"
                        ),
                        risk="medium",
                        requires_decision=True,
                        note="Şablon - üst tablo ve kolon adını doldur.",
                    ),
                ),
            )
        )
    return findings


# --------------------------------------------------------------------------
# R005 - circular foreign key chains
# --------------------------------------------------------------------------


def _cycle_key(cycle: list[str]) -> tuple[str, ...]:
    """Rotates a cycle so the same loop is never reported twice."""
    start = cycle.index(min(cycle))
    return tuple(cycle[start:] + cycle[:start])


def circular_foreign_keys(schema: Schema) -> list[Finding]:
    # A self-reference (employees.manager_id -> employees) is a normal way to
    # model a hierarchy, so it is not treated as a cycle.
    edges: dict[str, set[str]] = {}
    for fk in schema.foreign_keys:
        if fk.table != fk.target_table:
            edges.setdefault(fk.table, set()).add(fk.target_table)

    cycles: dict[tuple[str, ...], None] = {}
    visited: set[str] = set()
    stack: list[str] = []
    on_stack: set[str] = set()

    def visit(node: str) -> None:
        visited.add(node)
        stack.append(node)
        on_stack.add(node)
        for target in sorted(edges.get(node, ())):
            if target in on_stack:
                cycles.setdefault(_cycle_key(stack[stack.index(target) :]), None)
            elif target not in visited:
                visit(target)
        stack.pop()
        on_stack.discard(node)

    for table in sorted(schema.tables):
        if table not in visited:
            visit(table)

    findings = []
    for key in sorted(cycles):
        path = " -> ".join(key) + f" -> {key[0]}"
        findings.append(
            Finding(
                rule_id="R005",
                rule_name="Döngüsel foreign key zinciri",
                severity=ERROR,
                target=", ".join(key),
                message=f"Foreign key'ler döngü oluşturuyor: {path}.",
                rationale=(
                    "Döngüdeki hiçbir satır ilk sırada eklenemez; kayıtlar "
                    "ancak bir kısıt ertelenerek ya da bir kolon NULL bırakılıp "
                    "sonradan doldurularak oluşturulabilir. Grubu silmek de "
                    "aynı sorunu tersten yaşatır."
                ),
                remediations=(
                    Remediation(
                        label="Döngüyü kırmak için bir kısıtı ertele",
                        ddl=(
                            f"-- Döngüdeki en önemsiz bağı seç:\n"
                            f"ALTER TABLE {schema.name}.<tablo>\n"
                            f"    DROP CONSTRAINT <kisit>,\n"
                            f"    ADD CONSTRAINT <kisit>\n"
                            f"        FOREIGN KEY (<kolon>)\n"
                            f"        REFERENCES {schema.name}.<hedef> (id)\n"
                            f"        DEFERRABLE INITIALLY DEFERRED;"
                        ),
                        risk="medium",
                        requires_decision=True,
                        note=(
                            "Tek bir transaction'ın grubun tamamını eklemesine "
                            "izin verir."
                        ),
                    ),
                    Remediation(
                        label="En zayıf bağı ayrı bir tabloya taşı",
                        ddl="",
                        risk="high",
                        requires_decision=True,
                        note=(
                            "Yapısal çözüm: doğrudan referanslardan birini "
                            "bağlantı tablosuyla değiştirerek döngüyü ortadan "
                            "kaldır."
                        ),
                    ),
                ),
            )
        )
    return findings


