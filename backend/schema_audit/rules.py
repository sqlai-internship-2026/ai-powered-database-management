# R006 - duplicate and redundant indexes
# --------------------------------------------------------------------------


def redundant_index(schema: Schema) -> list[Finding]:
    findings = []
    for name in sorted(schema.tables):
        table = schema.tables[name]
        reported: set[str] = set()

        by_columns: dict[tuple[str, ...], list] = {}
        for index in table.indexes:
            by_columns.setdefault(index.columns, []).append(index)

        # Exact duplicates: same columns in the same order.
        for columns, group in sorted(by_columns.items()):
            if len(group) < 2:
                continue
            # Keep the primary key, then any unique index - those carry a
            # guarantee, not just an access path.
            group = sorted(
                group, key=lambda ix: (not ix.is_primary, not ix.is_unique, ix.name)
            )
            keep, extras = group[0], group[1:]
            for extra in extras:
                reported.add(extra.name)
                findings.append(
                    Finding(
                        rule_id="R006",
                        rule_name="Yinelenen index",
                        severity=WARNING,
                        target=f"{_q(schema, name)}.{extra.name}",
                        message=(
                            f'"{extra.name}" index\'i ({", ".join(columns)}) '
                            f'kolonlarını indeksliyor; "{keep.name}" bunu zaten '
                            f"kapsıyor."
                        ),
                        rationale=(
                            "Aynı index'in ikinci kopyası her insert, update ve "
                            "delete işleminde yeniden yazılır, disk ve önbellek "
                            "harcar ve planlayıcı tarafından birincisine tercih "
                            "edilmez."
                        ),
                        remediations=(
                            Remediation(
                                label=f"{extra.name} index'ini düşür",
                                ddl=f"DROP INDEX {schema.name}.{extra.name};",
                                risk="medium" if extra.is_unique else "low",
                                recommended=not extra.is_unique,
                                note=(
                                    "Bu index aynı zamanda benzersizliği "
                                    "zorluyor - kısıt adına bağlı bir şey "
                                    "olmadığını kontrol et."
                                    if extra.is_unique
                                    else "Saf kopya; kaldırmak güvenli."
                                ),
                            ),
                        ),
                    )
                )

        # Prefix redundancy: an index on (a) is dead weight when (a, b) exists.
        for index in sorted(table.indexes, key=lambda ix: ix.name):
            if index.is_primary or index.is_unique or index.name in reported:
                continue
            wider = [
                other.name
                for other in table.indexes
                if other.name != index.name
                and len(other.columns) > len(index.columns)
                and other.covers(index.columns)
            ]
            if not wider:
                continue
            covering = sorted(wider)[0]
            findings.append(
                Finding(
                    rule_id="R006",
                    rule_name="Gereksiz index ön eki",
                    severity=INFO,
                    target=f"{_q(schema, name)}.{index.name}",
                    message=(
                        f'"{index.name}" ({", ".join(index.columns)}) index\'i, '
                        f'"{covering}" index\'inin baştan alt kümesi.'
                    ),
                    rationale=(
                        "Bileşik bir index, baştaki kolonlarından başlayan "
                        "aramaları zaten karşılar; dar index yalnızca yazma "
                        "maliyeti ekler."
                    ),
                    remediations=(
                        Remediation(
                            label=f"{index.name} index'ini düşür",
                            ddl=f"DROP INDEX {schema.name}.{index.name};",
                            risk="low",
                            recommended=True,
                            note=(
                                f'"{covering}" aynı aramaları karşılamaya '
                                f"devam eder."
                            ),
                        ),
                    ),
                )
            )
    return findings


# --------------------------------------------------------------------------
# R007 - foreign key type mismatch
# --------------------------------------------------------------------------


def foreign_key_type_mismatch(schema: Schema) -> list[Finding]:
    findings = []
    for fk in schema.foreign_keys:
        source = schema.tables.get(fk.table)
        target = schema.tables.get(fk.target_table)
        if source is None or target is None:
            continue
        for column_name, target_name in zip(fk.columns, fk.target_columns):
            column = source.column(column_name)
            target_column = target.column(target_name)
            if column is None or target_column is None:
                continue
            if column.type_oid == target_column.type_oid:
                continue
            findings.append(
                Finding(
                    rule_id="R007",
                    rule_name="Foreign key tip uyuşmazlığı",
                    severity=ERROR,
                    target=f"{_q(schema, fk.table)}.{column_name}",
                    message=(
                        f"{fk.table}.{column_name} kolonu {column.data_type}, "
                        f"ama referans verdiği {fk.target_table}.{target_name} "
                        f"kolonu {target_column.data_type}."
                    ),
                    rationale=(
                        "PostgreSQL karşılaştırılabilir ama farklı tipler "
                        "arasında foreign key'e izin verir. Bu durumda her join "
                        "bir cast gerektirir; bu index kullanımını "
                        "engelleyebilir ve dar taraf geniş taraftan çok önce "
                        "taşar."
                    ),
                    remediations=(
                        Remediation(
                            label=(
                                f"{fk.table}.{column_name} kolonunu "
                                f"{target_column.data_type} tipine genişlet"
                            ),
                            ddl=(
                                f"ALTER TABLE {_q(schema, fk.table)}\n"
                                f"    ALTER COLUMN {column_name} TYPE "
                                f"{target_column.data_type};"
                            ),
                            risk="medium",
                            recommended=True,
                            note=(
                                "Tabloyu baştan yazar ve index'lerini yeniden "
                                "kurar."
                            ),
                        ),
                    ),
                )
            )
    return findings


